// Writes the compiled ABI to ../lib/contract/CampusCred.abi.ts for the Next app.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { artifacts } from "hardhat";

async function main() {
  const { abi } = await artifacts.readArtifact("CampusCred");
  const out = join(__dirname, "../../lib/contract/CampusCred.abi.ts");
  writeFileSync(
    out,
    `// Generated by hardhat/scripts/export-abi.ts. Do not edit by hand.\nexport const CAMPUSCRED_ABI = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  console.log(`wrote ${out} (${abi.length} entries)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
